// Basics like variables, datatypes
void main(){
  print("Hello World");

  // Datatypes
  String name= "Alice";
  int age= 25;
  bool value= true;

  print(name);
  print(age);
  print(value);

  // Nullable integer declaration
  int? num1;
  print(num1);

  // Using 'var' keyword (automatically detects type)
  var year= 2026;
  var month= "August";
  print(year);
  print(month);
} 